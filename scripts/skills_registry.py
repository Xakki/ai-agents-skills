#!/usr/bin/env python3
"""Maintain the skill naming registry, invocation metadata and skill catalog.

Usage from the project root:
  python3 scripts/skills_registry.py check    verify names, descriptions, metadata and catalog (no writes)
  python3 scripts/skills_registry.py apply    update invocation metadata and regenerate the catalog

Names follow <area>-<object>-<goal> (see skills-registry.json). Only the registry's
always tier permits automatic model invocation in Claude Code and Codex. Other
skills need explicit user invocation. Runtime permissions remain authoritative.
"""
import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SKILLS = ROOT / 'skills'
REGISTRY = json.loads((ROOT / 'skills-registry.json').read_text(encoding='utf-8'))
CATALOG = SKILLS / 'agent-skill-find' / 'references' / 'catalog.md'
FRONTMATTER = re.compile(r'\A---\n(.*?)\n---\n', re.S)
NAME = re.compile(r'^([a-z]+)-([a-z0-9]+(?:-[a-z0-9]+){0,2})-([a-z]+)$')
MAX_NAME, MAX_DESCRIPTION = 40, 400
ALLOWED_KEYS = {'name', 'description', 'license', 'disable-model-invocation'}


def read_skill(directory):
    text = (directory / 'SKILL.md').read_text(encoding='utf-8')
    match = FRONTMATTER.match(text)
    if not match:
        raise SystemExit(f'{directory.name}: missing frontmatter')
    return yaml.safe_load(match.group(1)) or {}, text[match.end():]


def write_frontmatter(directory, frontmatter, body):
    order = ['name', 'description'] + [key for key in frontmatter if key not in ('name', 'description')]
    head = ''.join(yaml.safe_dump({key: frontmatter[key]}, allow_unicode=True, width=100000, sort_keys=False)
                   for key in order)
    (directory / 'SKILL.md').write_text('---\n' + head + '---\n' + body, encoding='utf-8')


def policy_text(implicit):
    return 'policy:\n  allow_implicit_invocation: %s\n' % ('true' if implicit else 'false')


def skills():
    return sorted(path for path in SKILLS.iterdir() if path.is_dir())


def catalog_summary(description):
    """First sentence (what the skill does, shortened) and the Russian trigger words."""
    russian = re.search(r'RU: (.*?)\.?$', description)
    english = description[:russian.start()].strip() if russian else description
    first = re.split(r'(?<=[a-z0-9)`])\. ', english)[0].rstrip('.')
    if len(first) > 170:
        first = first[:167].rsplit(' ', 1)[0] + '...'
    return first, (russian.group(1) if russian else '')


def catalog_text(entries):
    lines = ['# Catalog of ai-agents-skills', '',
             'Generated by `scripts/skills_registry.py apply`; do not edit by hand.',
             'Skills marked * permit automatic model invocation in Claude Code and Codex.',
             'For other skills, ask the user to invoke the skill using the runtime\'s supported interface.',
             'Respect invocation restrictions and permission denials; do not reproduce a blocked skill',
             'by reading its file. Supporting files of an invoked skill remain usable as its dependencies.', '']
    by_area = {}
    for name, description in entries:
        by_area.setdefault(name.split('-')[0], []).append((name, description))
    for area in sorted(by_area):
        lines += [f'## {area}: {REGISTRY["areas"][area]}', '']
        for name, description in by_area[area]:
            what, russian = catalog_summary(description)
            mark = '*' if name in REGISTRY['tiers']['always'] else ''
            lines.append(f'- `{name}`{mark}: {what}' + (f' [{russian}]' if russian else ''))
        lines.append('')
    return '\n'.join(lines)


def run(write):
    problems = []
    always = set(REGISTRY['tiers']['always'])
    entries = []
    for directory in skills():
        name = directory.name
        try:
            frontmatter, body = read_skill(directory)
        except SystemExit as error:
            problems.append(str(error))
            continue
        match = NAME.match(name)
        if not match or len(name) > MAX_NAME:
            problems.append(f'{name}: name does not match <area>-<object>-<goal> or exceeds {MAX_NAME}')
        else:
            if match.group(1) not in REGISTRY['areas']:
                problems.append(f'{name}: unknown area {match.group(1)}')
            if match.group(3) not in REGISTRY['goals']:
                problems.append(f'{name}: unknown goal {match.group(3)}')
        if frontmatter.get('name') != name:
            problems.append(f'{name}: frontmatter name is {frontmatter.get("name")}')
        description = ' '.join(str(frontmatter.get('description', '')).split())
        if not description or len(description) > MAX_DESCRIPTION or not re.search(r'\bUse\b', description):
            problems.append(f'{name}: description must be non-empty, <= {MAX_DESCRIPTION} chars and say when to Use it')
        extra = set(frontmatter) - ALLOWED_KEYS
        if extra:
            problems.append(f'{name}: unexpected frontmatter keys {sorted(extra)}')
        for nested in directory.rglob('SKILL.md'):
            if nested != directory / 'SKILL.md':
                problems.append(f'{name}: nested skill {nested.relative_to(SKILLS)}')
        entries.append((name, description))
        implicit = name in always
        wanted_hidden = not implicit
        if frontmatter.get('disable-model-invocation', False) is not wanted_hidden:
            if write:
                if wanted_hidden:
                    frontmatter['disable-model-invocation'] = True
                else:
                    frontmatter.pop('disable-model-invocation', None)
                write_frontmatter(directory, frontmatter, body)
            else:
                problems.append(f'{name}: disable-model-invocation should be {wanted_hidden}')
        policy = directory / 'agents' / 'openai.yaml'
        if not policy.exists() or policy.read_text(encoding='utf-8') != policy_text(implicit):
            if write:
                policy.parent.mkdir(exist_ok=True)
                policy.write_text(policy_text(implicit), encoding='utf-8')
            else:
                problems.append(f'{name}: agents/openai.yaml should set allow_implicit_invocation: {implicit}')
    for name in always - {entry[0] for entry in entries}:
        problems.append(f'{name}: listed as always-on but does not exist')
    expected = catalog_text(entries)
    if not CATALOG.exists() or CATALOG.read_text(encoding='utf-8') != expected:
        if write:
            CATALOG.parent.mkdir(parents=True, exist_ok=True)
            CATALOG.write_text(expected, encoding='utf-8')
        else:
            problems.append('skills/agent-skill-find/references/catalog.md is out of date')
    return problems


if __name__ == '__main__':
    if len(sys.argv) != 2 or sys.argv[1] not in ('check', 'apply'):
        raise SystemExit(__doc__)
    found = run(sys.argv[1] == 'apply')
    if sys.argv[1] == 'apply':
        found = run(False)
    print('\n'.join(found) if found else 'ok: %d skills' % len(skills()))
    raise SystemExit(1 if found else 0)
